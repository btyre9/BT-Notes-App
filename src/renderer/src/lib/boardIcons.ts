export const DEFAULT_BOARD_ICON = 'layout-grid'

/** A board's icon from its file, ignoring anything that isn't a valid one. */
export function boardIconOf(data: CanvasData | undefined): BoardIcon {
  const raw = data?.btIcon
  if (typeof raw !== 'object' || raw === null) return {}
  const { icon, color, image } = raw as Record<string, unknown>
  return {
    icon: typeof icon === 'string' && Object.hasOwn(BOARD_ICONS, icon) ? icon : undefined,
    color: typeof color === 'string' && colorOf(color) ? color : undefined,
    image: typeof image === 'string' && image ? image : undefined,
  }
}
